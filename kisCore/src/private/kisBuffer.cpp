#include "kisBuffer.h"

#include <cstring>

//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
kisBuffer::kisBuffer(size_t size, uint32_t alignment)
{
    m_data = (uint8_t*)KIS_ALIGNED_ALLOC(size, alignment, "kisBuffer");
    m_ptr = m_data;
    m_size = size;
}

//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
kisBuffer::~kisBuffer()
{
    kisMemFree(m_data);
}

//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
void* kisBuffer::getStart() const
{
    return m_data;
}

//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
void* kisBuffer::getOffset() const
{
    KIS_ASSERT(m_ptr < m_data + m_size);
    return m_ptr;
}

//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
void kisBuffer::commit(size_t size)
{
    KIS_ASSERT(m_ptr + size <= m_data + m_size);
    m_ptr += size;
}

//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
void kisBuffer::copyAndCommit(void* src, size_t size)
{
    KIS_ASSERT(m_ptr + size <= m_data + m_size);
    memcpy(m_ptr, src, size);
    m_ptr += size;
}
