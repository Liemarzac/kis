#pragma once

#include "kisCoreShared.h"

#include <string.h>


//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
struct kisHash128
{
    uint8_t bytes[16];
};

//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
inline bool operator==(const kisHash128& a, const kisHash128& b)
{
    return memcmp(&a, &b, sizeof(kisHash128)) == 0;
}

//--------------------------------------------------------------------------
//--------------------------------------------------------------------------
inline bool operator!=(const kisHash128& a, const kisHash128& b)
{
    return memcmp(&a, &b, sizeof(kisHash128)) != 0;
}

